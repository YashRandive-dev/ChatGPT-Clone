export const LANGUAGES: { value: Language; label: string }[] = [
  { value: 'en', label: 'English' },
  { value: 'es', label: 'Español' },
  { value: 'fr', label: 'Français' },
  { value: 'de', label: 'Deutsch' },
  { value: 'hi', label: 'हिन्दी' },
];

type TFn = (key: TKey, vars?: Record<string, string>) => string;
const I18nContext = createContext<{ lang: Language; t: TFn }>({
  lang: 'en',
  t: (k, vars) => interpolate(en[k], vars),
});

function interpolate(s: string, vars?: Record<string, string>) {
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '') : s;
}

export function I18nProvider({ lang, children }: { lang: Language; children: ReactNode }) {
  const t = useCallback<TFn>((key, vars) => interpolate(dictionaries[lang]?.[key] ?? en[key] ?? key, vars), [lang]);
  const value = useMemo(() => ({ lang, t }), [lang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useT = () => useContext(I18nContext);
